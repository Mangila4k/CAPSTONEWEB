    // 6. SECTIONS CAPACITY REPORT
    async function generateSectionsCapacityReport(grade, strand) {
        if (displayReportTitle) displayReportTitle.textContent = 'Sections Masterlist & Room Capacity';
        if (displayReportSubtitle) displayReportSubtitle.textContent = 'Classroom utilization, student counts vs capacity limits, and adviser assignments';

        const [{ data: sections, error: sErr }, { data: students }, { data: teachers }] = await Promise.all([
            supabase.from('sections').select('*').order('name', { ascending: true }),
            supabase.from('students').select('id, section'),
            supabase.from('teachers').select('id, fullname')
        ]);

        if (sErr) throw sErr;
        const teacherMap = {};
        (teachers || []).forEach(t => { teacherMap[t.id] = t.fullname; });

        let list = (sections || []).map(sec => {
            const enrolled = (students || []).filter(s => s.section === sec.name || s.section === sec.id).length;
            const capacity = sec.capacity || 45;
            const available = Math.max(0, capacity - enrolled);
            const pct = Math.round((enrolled / capacity) * 100);
            const adviser = teacherMap[sec.adviser_id] || sec.adviser_name || 'Unassigned';

            return {
                name: sec.name,
                grade: sec.grade_level || 'Grade 11',
                strand: sec.strand || '—',
                room: sec.room || 'Room 101',
                adviser,
                enrolled,
                capacity,
                available,
                pct
            };
        });

        if (grade) list = list.filter(s => s.grade.toLowerCase().includes(grade.toLowerCase()));
        if (strand) list = list.filter(s => s.strand.toLowerCase().includes(strand.toLowerCase()));

        currentHeaders = ['#', 'Section Name', 'Grade Level', 'Strand', 'Room', 'Class Adviser', 'Enrolled', 'Capacity', 'Available', 'Occupancy'];
        currentRawData = list.map((s, index) => {
            const occClass = s.pct >= 90 ? 'danger' : s.pct >= 75 ? 'warning' : 'success';
            return {
                cells: [
                    index + 1,
                    `<strong>${s.name}</strong>`,
                    s.grade,
                    s.strand,
                    s.room,
                    s.adviser,
                    s.enrolled,
                    s.capacity,
                    s.available,
                    `<span class="status-badge ${occClass}">${s.pct}% (${s.available > 0 ? `${s.available} slots` : 'FULL'})</span>`
                ],
                exportRow: [index + 1, s.name, s.grade, s.strand, s.room, s.adviser, s.enrolled, s.capacity, s.available, `${s.pct}%`],
                searchString: `${s.name} ${s.grade} ${s.strand} ${s.room} ${s.adviser} ${s.enrolled} ${s.capacity} ${s.available}`.toLowerCase()
            };
        });
    }

