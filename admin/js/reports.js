    // DATE PRESET HANDLING
    // ============================================
    function setDatePreset(rangeType) {
        const today = new Date();
        let fromDate = '';
        let toDate = today.toISOString().split('T')[0];

        switch (rangeType) {
            case 'today':
                fromDate = toDate;
                break;
            case 'week':
                const lastWeek = new Date();
                lastWeek.setDate(today.getDate() - 7);
                fromDate = lastWeek.toISOString().split('T')[0];
                break;
            case 'month':
                const startOfMonth = new Date(today.getFullYear(), today.getMonth(), 1);
                fromDate = startOfMonth.toISOString().split('T')[0];
                break;
            case 'year':
                const curYear = today.getFullYear();
                const schoolYearStart = today.getMonth() >= 5 ? new Date(curYear, 5, 1) : new Date(curYear - 1, 5, 1);
                fromDate = schoolYearStart.toISOString().split('T')[0];
                break;
            case 'all':
            default:
                fromDate = '';
                toDate = '';
                break;
        }

        if (dateFrom) dateFrom.value = fromDate;
        if (dateTo) dateTo.value = toDate;
    }

